// Generates src/generated/contracts.ts from the Foundry artifacts (../out) and
// the deployment record (../deployments/<chainId>.json).
//
//   npm run gen:contracts          write the file
//   npm run gen:contracts -- --check   exit 1 if the committed file is stale
//
// Run `forge build` in the repo root first: out/ is gitignored, so the output
// of this script is what Vercel builds against.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { getAddress } from "viem";

const CHAIN_ID = 11155111;
const REPO_ROOT = resolve(import.meta.dirname, "..", "..");
const OUTPUT = resolve(import.meta.dirname, "..", "src", "generated", "contracts.ts");

// Contract name (Foundry artifact) -> key in deployments/<chainId>.json.
// FundTreasury is a UUPS proxy: the implementation ABI is used at the proxy address.
const CONTRACTS = {
  FundShare: "token",
  FundGovernor: "governor",
  TimelockController: "timelock",
  ArtRegistry: "registry",
  FundTreasury: "treasuryProxy",
} as const;

function readJson(path: string): unknown {
  if (!existsSync(path)) throw new Error(`Missing ${path}. Did you run \`forge build\`?`);
  return JSON.parse(readFileSync(path, "utf8"));
}

function render(): string {
  const deployment = readJson(join(REPO_ROOT, "deployments", `${CHAIN_ID}.json`)) as Record<string, string>;

  const blocks = Object.entries(CONTRACTS).map(([name, key]) => {
    const raw = deployment[key];
    if (!raw) throw new Error(`deployments/${CHAIN_ID}.json has no "${key}" (needed for ${name})`);
    const address = getAddress(raw);
    const { abi } = readJson(join(REPO_ROOT, "out", `${name}.sol`, `${name}.json`)) as { abi: unknown[] };
    return `export const ${name} = {\n  address: "${address}" as Address,\n  abi: ${JSON.stringify(abi, null, 2).replace(/\n/g, "\n  ")} as const,\n} as const;`;
  });

  return [
    "// GENERATED by scripts/gen-contracts.ts. Do not edit; run `npm run gen:contracts`.",
    'import type { Address } from "viem";',
    "",
    `export const CHAIN_ID = ${CHAIN_ID};`,
    "",
    blocks.join("\n\n"),
    "",
  ].join("\n");
}

const next = render();

if (process.argv.includes("--check")) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : "";
  if (current !== next) {
    console.error(`${OUTPUT} is stale. Run \`forge build\` then \`npm run gen:contracts\` and commit.`);
    process.exit(1);
  }
  console.log("contracts.ts is up to date.");
} else {
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, next);
  console.log(`Wrote ${OUTPUT}`);
}
